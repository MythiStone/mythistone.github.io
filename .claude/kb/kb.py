def main(argv):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # gotchas hold characters a cp1252 Windows console cannot encode
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__ + "\nTools:\n" + "\n".join(f"  {name[3:]:<12} {desc}" for name, (desc, _, _) in TOOLS.items()))
        return 0
    kb = KB()
    if argv[0] == "--strict":
        print(kb.lint_strict())
        return 0
    if argv[0] == "--index":
        print(kb.write_indexes())
        return 0
    cmd = argv[0]
    name = cmd if cmd.startswith("kb_") else "kb_" + {"bot": "bot_command"}.get(cmd, cmd.replace("-", "_"))
    if name not in TOOLS:
        print(f"unknown command {argv[0]}; one of: {', '.join(t[3:] for t in TOOLS)}", file=sys.stderr)
        return 2
    _, params, fn = TOOLS[name]
    print(fn(kb, *[" ".join(argv[1:])] if params else []))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

    def search(self, query, limit=30):
        q = query.lower()
        out = []
        for gid, g in self.gotchas.items():
            if q in gid.lower() or q in g["rule"].lower():
                out.append(f"gotcha {gid}: {g['rule'][:200]}")
            else:
                for line in g["body"].splitlines():
                    if q in line.lower():
                        out.append(f"gotcha {gid}: ...{line.strip()[:200]}")
                        break
        out += [f"table {t}" for t in self.tables if q in t]
        out += [f"routine {r}" for r in self.routines if q in r.lower()]
        out += [f"{d['kind']} {n} ({d['file']}:{d['line']})" for n, ds in self.defs.items() if q in n.lower() for d in ds]
        out += [f"bot /{c}" for c in self.bot_commands if q in c]
        return "\n".join(out[:limit]) + (f"\n... {len(out) - limit} more" if len(out) > limit else "") if out else f"No match for `{query}`."

    def _source_words(self):
        words = set()
        for f in self.files:
            if f.startswith(".claude/") or not f.endswith((".py", ".sql", ".html", ".js", ".css", ".yml", ".yaml", ".sh", ".md")):
                continue
            try:
                if os.path.getsize(ROOT / f) < 3_000_000:
                    words |= set(re.findall(r"[A-Za-z_]\w*", (ROOT / f).read_text(encoding="utf-8", errors="ignore")))
            except OSError:
                pass
        return words

    def lint_strict(self):
        """lint plus the checks that need a human: cited names that appear nowhere in the source,
        sentences that echo a docstring or comment of the code they cite, and oversized gotchas.
        Expect noise (external API fields, MySQL internals); review, do not auto-fix."""
        words = self._source_words()
        unknown, echoes, big = [], [], []
        grams = {}
        for gid, g in sorted(self.gotchas.items()):
            names = set()
            for tok in re.findall(r"`([^`\n]+)`", _prose(g["body"])):
                for ident in re.findall(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*", tok):
                    last = ident.split(".")[-1]
                    if len(last) >= 4 and ("_" in last.strip("_") or re.search(r"[a-z][A-Z]", last)) and last not in words:
                        names.add(ident)
            if names:
                unknown.append(f"{g['path']}: {', '.join(sorted(names))}")
            if g["index"]:
                continue
            if len(g["body"]) > SIZE_BUDGET:
                big.append(f"{g['path']}: {len(g['body'])} chars")
            echoes += self._echoes(g, grams)
        sections = [
            ("unverified names (not found in source)", unknown),
            ("sentences that echo a comment or docstring of the cited code", echoes),
            (f"gotchas over {SIZE_BUDGET} chars (usually narrating code)", big),
        ]
        return self.lint() + "".join(f"\n\n{title}: " + ("\n" + "\n".join(rows) if rows else "none") for title, rows in sections)

    def _comment_grams(self, rel, cache):
        """Word 4-grams of a source file's docstrings and comments."""
        if rel not in cache:
            text = self._read(rel) if (ROOT / rel).is_file() and os.path.getsize(ROOT / rel) < 600_000 else ""
            if rel.endswith(".py"):
                parts = re.findall(r'"""(.*?)"""', text, re.S) + [" ".join(re.findall(r"#\s?([^\n]*)", text))]
            elif rel.endswith((".js", ".css", ".scss")):
                parts = re.findall(r"/\*(.*?)\*/", text, re.S) + [" ".join(re.findall(r"//\s?([^\n]*)", text))]
            elif rel.endswith(".sql"):
                parts = [" ".join(re.findall(r"--\s?([^\n]*)", text))] + re.findall(r"/\*(.*?)\*/", text, re.S)
            elif rel.endswith(".html"):
                parts = re.findall(r"\{#(.*?)#\}", text, re.S) + re.findall(r"<!--(.*?)-->", text, re.S)
            elif rel.endswith((".sh", ".yml", ".yaml")) or "Dockerfile" in rel:
                parts = [" ".join(re.findall(r"#\s?([^\n]*)", text))]
            else:
                parts = []
            out = set()
            for part in parts:
                w = re.findall(r"[a-z0-9_]+", part.lower())
                out |= {tuple(w[i:i + 4]) for i in range(len(w) - 3)}
            cache[rel] = out
        return cache[rel]

    def _echoes(self, g, cache):
        symbols, _, paths = self.cited(g["body"])
        files = {f for locs in symbols.values() for f, _ in locs} | paths
        files |= {f for f in self.files if any(_match(f, p) for p in g["files"])}
        out = []
        for s in _sentences(g["body"]):
            w = re.findall(r"[a-z0-9_]+", s.lower())
            if len(w) < 10:
                continue
            mine = {tuple(w[i:i + 4]) for i in range(len(w) - 3)}
            share, best = max(((len(mine & self._comment_grams(f, cache)) / len(mine), f) for f in files), default=(0, ""))
            if share >= ECHO_SHARE:
                out.append(f"{g['path']}: {share:.0%} in {best}: \"{s[:110]}\"")
        return out

    def _duplication(self, g):
        """Second copies of code inside one gotcha: a coupling that names a single site, a restated
        signature, a restated column list."""
        out = []
        symbols, _, paths = self.cited(g["body"])
        if g["kind"] not in KINDS:
            out.append(f"{g['path']}: kind `{g['kind']}` is not one of {', '.join(KINDS)}")
        if g["kind"] == "coupling":
            homes = {f for locs in symbols.values() for f, _ in locs}
            sites = set(symbols) | (paths - homes)
            if len(sites) < 2:
                out.append(f"{g['path']}: a coupling names at least two code sites, this names {len(sites)}; "
                           "a single-site fact belongs in a short code comment or nowhere")
        for tok in sorted(set(re.findall(r"`([^`\n]+)`", _prose(g["body"])))):
            m = re.fullmatch(r"([\w.]+)\((.+)\)", tok.strip())
            if not m:
                continue
            name = m.group(1).split(".")[-1]
            given = {p.split("=")[0].strip(" *") for p in m.group(2).split(",")}
            if any(len(given & set(d.get("args", ()))) >= 2 for d in self.defs.get(name, [])):
                out.append(f"{g['path']}: `{tok}` restates the signature of {name}; name the symbol only")
        for s in _sentences(g["body"]):
            ticks = {t.strip() for t in re.findall(r"`([^`\n]+)`", s)}
            for t, rx in self._table_re.items():
                if not rx.search(s):
                    continue
                cols = {c for c, _ in self.tables[t]["cols"]}
                listed = ticks & cols
                paren = re.search(r"\b" + re.escape(t) + r"`?\s*\(([^`\n]*)", s, re.I)
                if paren:
                    listed |= set(re.findall(r"\w+", paren.group(1))) & cols
                if len(listed) >= 3:
                    out.append(f"{g['path']}: lists columns of `{t}` ({', '.join(sorted(listed))}); the table lookup derives them")
        return out

    def lint(self):
        """Problems in the curated knowledge: cited paths/symbols/links that no longer exist, gotchas
        that restate code, generated tables that drifted, and kb tool names that do not exist."""
        corpus_files = set(self.files)
        known = set(self.defs) | set(self.routines) | set(self.tables)
        problems = []
        generated = ("assets/json/", "data/bot_cache/", "data/state/", "sim_results", "simc_profiles", "_site")
        for gid, g in sorted(self.gotchas.items()):
            for pat in g["files"]:
                if not any(_match(f, pat) for f in corpus_files):
                    problems.append(f"{g['path']}: files glob `{pat}` matches nothing")
            prose = _prose(g["body"])
            for tok in set(re.findall(r"`([^`\s]+)`", prose)):
                t = tok.rstrip("(),.:;")
                if re.search(r"[*<>{}$]", t):
                    continue
                if "/" in t and re.search(r"\.(py|sql|html|js|css|yml|yaml|sh|json|md)$", t):
                    t = t.lstrip("/")
                    if t.startswith(generated) or t.startswith("plugins/"):
                        continue
                    if not any(f == t or f.endswith("/" + t) for f in corpus_files):
                        problems.append(f"{g['path']}: path `{tok}` not found")
                elif re.fullmatch(r"(sp|ev|fn)_\w+|fetch_\w+|[A-Z][A-Z0-9_]+_SQL", t.rstrip("()")):
                    if t.rstrip("()") not in known:
                        problems.append(f"{g['path']}: symbol `{tok}` not found")
            for ref in re.findall(r"\[\[([\w-]+)\]\]", re.sub(r"`[^`]*`", "", prose)):
                if ref not in self.gotchas:
                    problems.append(f"{g['path']}: link [[{ref}]] has no gotcha")
            if g["kind"]:
                problems += self._duplication(g)
            elif not g["index"]:
                problems.append(f"{g['path']}: no `kind:` ({', '.join(KINDS)})")
        problems += [f"{_rel(p)}: generated table is out of date, run `python .claude/kb/kb.py --index`"
                     for p, text in self.index_outputs().items() if p.read_text(encoding="utf-8") != text]
        docs = [ROOT / "AGENTS.md", ROOT / ".claude" / "CLAUDE.md", *sorted(SKILLS_DIR.glob("**/*.md")), *sorted(AGENTS_DIR.glob("*.md"))]
        for p in docs:
            for name in sorted(set(re.findall(r"\bkb_[a-z_]+\b", p.read_text(encoding="utf-8", errors="ignore"))) - set(TOOLS)):
                problems.append(f"{_rel(p)}: `{name}` is not a kb tool")
        return "kb lint: clean" if not problems else f"kb lint: {len(problems)} problem(s)\n" + "\n".join(problems)

